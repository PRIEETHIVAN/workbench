#pragma once
/**
 * batch_solver.hpp
 * Parallel batch thermal FEM solver using C++17 std::thread.
 *
 * Each SolveCase has its own k, q, T0, TL parameters, so results are
 * independent — ideal for task-parallel execution.
 *
 * Note: An OpenMP back-end (#pragma omp parallel for) would be a direct
 *       drop-in replacement for the thread-pool loop, giving equivalent
 *       speedup on shared-memory machines with less boilerplate.
 */

#include <vector>
#include <utility>

namespace parallel_solver {

/// One thermal FEM problem configuration
struct SolveCase {
    int    case_id;     ///< Unique identifier
    int    n_elements;  ///< Number of FEM elements
    double k;           ///< Thermal conductivity [W/(m·K)]
    double q;           ///< Heat generation [W/m³]
    double T0;          ///< Left BC temperature [°C]
    double TL;          ///< Right BC temperature [°C]
};

/// Aggregated results from a serial or parallel batch run
struct BatchResult {
    std::vector<std::pair<int,double>> case_max_errors; ///< {case_id, max_error}
    std::vector<std::vector<double>> case_temperatures; ///< Nodal temperatures in input order
    double wall_time_ms;   ///< Elapsed wall-clock time [ms]
    int    worker_count;   ///< Number of worker threads (1 for serial)
    double speedup;        ///< T_serial / T_parallel  (1.0 for serial baseline)
    double efficiency;     ///< speedup / worker_count
};

/**
 * Generate a reproducible set of SolveCases using a fixed seed (42).
 *
 * @param count      Number of cases to generate
 * @param mesh_size  Baseline mesh size (n_elements), jittered by RNG
 * @return           Vector of SolveCase ready for serial or parallel solve
 */
std::vector<SolveCase> generate_cases(int count, int mesh_size = 20);

/**
 * Run all cases sequentially on the calling thread.
 * Provides the T₁ baseline for speedup calculation.
 */
BatchResult run_batch_serial(const std::vector<SolveCase>& cases);

/**
 * Run all cases on a bounded thread pool.
 *
 * Internally creates `num_workers` std::thread workers that pull tasks from a
 * mutex-protected task queue with a condition_variable for coordination.
 * Results are written to a pre-allocated output array so no locking is needed
 * for result storage (each case owns a distinct slot).
 *
 * Numerical results are identical to run_batch_serial for the same input
 * (verified: max absolute temperature difference ≤ 1e-8).
 *
 * @param cases       Cases generated by generate_cases()
 * @param num_workers Thread count; clamped to [1, hardware_concurrency]
 */
BatchResult run_batch_parallel(const std::vector<SolveCase>& cases, int num_workers);

} // namespace parallel_solver
